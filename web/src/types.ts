/**
 * Data model for Commodity Flows Atlas.
 *
 * Every number shown in the UI must be traceable to a source and a year.
 * The canonical data lives in /data (repo root) and is served at ./data/.
 * See docs/DATA_MODEL.md for the full description of each file.
 */

export type Family = 'energy' | 'metals' | 'softs' | 'freight';

/** ISO 3166-1 alpha-3 country code, or a region code such as "EU27" / "WLD". */
export type Iso3 = string;

/** A sourced, dated figure. */
export interface Fig {
  /** value */
  v: number;
  /** unit, e.g. "Mt", "kb/d", "bcm", "%" */
  u: string;
  /** reference year (number) or period label such as "2024/25" or "2025-Q2" */
  y: number | string;
  /** source id, key into sources.json */
  s: string;
  /** optional note (method, discrepancy, scope) */
  n?: string;
}

/** Entry of data/sources.json */
export interface Source {
  id: string;
  name: string;
  publisher: string;
  url: string;
  licence: string;
  /** human-readable update cadence, e.g. "annual (January)" */
  update: string;
}

/** A ranked country table (production, reserves, exports...). Shares are computed against `world`. */
export interface Ranked {
  y: number | string;
  s: string;
  u: string;
  /** world total in the same unit, if known (from the same source) */
  world?: number;
  rows: { c: Iso3; v: number; n?: string }[];
  n?: string;
}

export interface Company {
  name: string;
  /** headquarters country */
  hq?: Iso3;
  /** e.g. "producer", "refiner", "smelter", "trader", "shipowner" */
  role: string;
  detail?: string;
  fig?: Fig;
  s?: string;
  y?: number | string;
  /** source page */
  url?: string;
  /** commodity id(s) the company is listed for (country profiles) */
  k?: string | string[];
}

/** A bilateral physical trade flow. */
export interface Flow {
  /** origin country */
  o: Iso3;
  /** destination country */
  d: Iso3;
  v: number;
  u: string;
  y: number | string;
  s: string;
  mode?: 'sea' | 'pipeline' | 'rail' | 'mixed';
  /** lane id in freight/lanes (sea geometry), when available */
  lane?: string;
  n?: string;
}

export interface CommodityMeta {
  id: string;
  name: string;
  family: Family;
  /** short one-line description */
  blurb: string;
  /** main physical unit */
  unit: string;
  hs?: string[];
  /** price series ids available for this commodity */
  prices?: string[];
  /** which panels/layers have data */
  has: Array<'production' | 'reserves' | 'consumption' | 'exports' | 'imports' | 'flows' | 'infrastructure' | 'prices' | 'companies'>;
  /** display order inside its family */
  rank: number;
}

export interface CommodityData {
  id: string;
  summary: Partial<Record<'production' | 'exports' | 'reserves' | 'consumption' | 'seaborne', Fig>>;
  production?: Ranked;
  /** refinery / smelter output by country */
  refinery?: Ranked;
  reserves?: Ranked;
  consumption?: Ranked;
  exports?: Ranked;
  imports?: Ranked;
  flows?: Flow[];
  companies?: { producers?: Company[]; processors?: Company[]; traders?: Company[] };
  notes?: string[];
  discrepancies?: string[];
}

export interface CountryMeta {
  c: Iso3;
  name: string;
  /** label anchor [lon, lat] */
  at: [number, number];
  /** bounding box [west, south, east, north]; east may exceed 180 for antimeridian countries */
  bb?: [number, number, number, number];
  region: string;
}

/** A country's ranked commodity profile, generated by pipeline/build_profiles.py */
export interface CountryProfile {
  c: Iso3;
  exports: ProfileEntry[];
  imports: ProfileEntry[];
  production: ProfileEntry[];
  /** commodities outside the main list (e.g. diamonds), minimal entries */
  other?: ProfileEntry[];
  infra?: string[];
  companies?: Company[];
}

export interface ProfileEntry {
  /** commodity id */
  k: string;
  /** label for non-catalogue commodities */
  label?: string;
  v: number;
  u: string;
  /** share of world total, 0..1 */
  share?: number;
  /** world rank */
  rank?: number;
  y: number | string;
  s: string;
  n?: string;
  /** trade value in bn USD, when known */
  usd?: number;
}

// ---------------------------------------------------------------- freight

export type Segment = 'dry' | 'tanker' | 'gas' | 'container';

export interface VesselClass {
  id: string;
  name: string;
  segment: Segment;
  /** deadweight range in tonnes (or cbm for gas carriers, see unit) */
  size: { min: number; max: number; typical: number; u: 'dwt' | 'cbm' | 'teu' };
  dims?: { loa?: number; beam?: number; draft?: number };
  cargoes: string[];
  constraints: string[];
  canals: { suez: string; panama: string };
  fleet?: Fig;
  routes: string[];
  notes?: string;
  s: string;
}

export interface PortRef {
  id: string;
  name: string;
  c: Iso3;
  at: [number, number];
}

export interface AltRouting {
  /** e.g. "Avoiding Suez Canal and Bab el-Mandeb (via Cape of Good Hope)" */
  label: string;
  avoids?: string[];
  via: string[];
  distanceNm: number;
  /** extra laden days vs the main routing (negative = the alternative is shorter) */
  extraDays: number;
  when?: string;
}

export interface Route {
  id: string;
  name: string;
  /** true for Baltic Exchange benchmark routes */
  benchmark: boolean;
  discontinued?: string;
  roundVoyage?: boolean;
  /** "typical laden leg" when a time-charter trip is drawn as its laden leg */
  drawnAs?: string;
  vclass: string;
  cargoes: string[];
  from: { region: string; ports: string[] };
  to: { region: string; ports: string[] };
  parcel?: number;
  parcelUnit?: 't' | 'cbm';
  distanceNm: number;
  /** laden voyage days at the class's typical laden speed */
  days: number;
  speedKn: number;
  /** chokepoint ids crossed, in order */
  via: string[];
  /** route end points [lon, lat] */
  a: [number, number];
  b: [number, number];
  /** bilateral flows this route represents: commodity id, origin and destination ISO3 lists */
  corridor?: { k: string; o: string[]; d: string[] }[];
  /** share of each cargo's seaborne trade carried on this corridor */
  shares?: { k: string; f: Fig }[];
  shareCommodity?: Fig;
  /** share of the vessel size class's tonne-mile demand (Atlas estimate) */
  shareClass?: Fig;
  alt?: AltRouting;
  /** annual corridor volumes, all cargoes of the corridor */
  history?: { y: number; v: number }[];
  historyUnit?: string;
  historySrc?: string;
  /** e.g. "Isolated customs outlier removed for 2016" */
  historyNote?: string;
  notes?: string;
  s: string;
}

export interface Chokepoint {
  id: string;
  name: string;
  kind: 'strait' | 'canal' | 'cape' | 'channel';
  at: [number, number];
  limits?: string;
  traffic?: Fig;
  /** published commodity flows through the chokepoint; k may be a commodity id or "petroleum-liquids" */
  shares?: { k: string; f: Fig }[];
  /** Atlas estimates: share of seaborne trade on mapped lanes crossing it */
  estimates?: { k: string; f: Fig }[];
  alternatives?: { label: string; extraNm?: number; extraDays?: number; note?: string }[];
  events?: string[];
  portwatch?: string;
  summary: string;
  s: string;
}

/** data/freight/portwatch/<id>.json — weekly averages of daily transits since 2019 */
export interface PortwatchSeries {
  id: string;
  s: string;
  /** last date in the data */
  y: string;
  unit: string;
  /** first week start, ISO date */
  start: string;
  step: 'week';
  tanker: number[];
  dry: number[];
  container: number[];
  other: number[];
  total: number[];
  /** deadweight capacity, million tonnes per day */
  dwt: number[];
}

export interface FreightEvent {
  id: string;
  date: string;
  end?: string;
  title: string;
  kind: 'conflict' | 'canal' | 'weather' | 'policy' | 'accident' | 'market' | 'infrastructure';
  chokepoints?: string[];
  routes?: string[];
  summary: string;
  impact?: string;
  src: string;
}

/** A seaborne lane: origin-destination country pair for one commodity group, with geometry. */
export interface Lane {
  /** "<group>:<o>-<d>" */
  id: string;
  /** atlas commodity id */
  k: string;
  /** commodity group (customs product group), e.g. "copper-ore" */
  p: string;
  o: Iso3;
  d: Iso3;
  /** port ids, see LaneFile.ports */
  load: string[];
  discharge: string[];
  /** typical vessel classes, primary first (Atlas assumption) */
  vclass: string[];
  distanceNm: number;
  days: number;
  via: string[];
  /** latest-year flow */
  flow: Fig;
  /** share of the group's seaborne trade, 0..1 (latest year) */
  share: number;
  /** share of the destination's imports of this group, 0..1 */
  shareDest?: number | null;
  /** annual volumes (LaneFile.unit) for LaneFile.years; null = isolated customs outlier removed */
  hist: (number | null)[];
  histNote?: string;
  /** geometry [lon, lat][]; longitudes are unwrapped (may exceed ±180) */
  g: [number, number][];
  alt?: AltRouting & { g: [number, number][] };
}

/** data/freight/lanes/<group>.json */
export interface LaneFile {
  group: string;
  k: string;
  label?: string | null;
  unit: string;
  y: number;
  s: string;
  years: number[];
  /** seaborne total per year (unit) */
  seaborne: number[];
  /** all-modes world trade per year (unit) */
  world: number[];
  ports: Record<string, PortRef>;
  lanes: Lane[];
}

// ---------------------------------------------------------------- infra & prices

export type InfraType =
  | 'mine'
  | 'field'
  | 'refinery'
  | 'lng-export'
  | 'lng-import'
  | 'pipeline'
  | 'smelter'
  | 'port';

export interface InfraProps {
  id: string;
  name: string;
  type: InfraType;
  k: string[];
  c: Iso3;
  operator?: string;
  capacity?: { v: number; u: string };
  opened?: number;
  status?: string;
  note?: string;
  s: string;
  y: number | string;
  /** countries crossed (pipelines) */
  cs?: Iso3[];
  /** source page */
  url?: string;
}

export interface PriceSeriesMeta {
  id: string;
  k: string;
  name: string;
  unit: string;
  freq: 'D' | 'M';
  s: string;
  start: string;
  end: string;
  /** e.g. "Updated on November 03, 2026" */
  note?: string;
  /** what the price measures (benchmark basis, series breaks) */
  basis?: string;
}

/** Packed price series. Monthly: start "YYYY-MM" + consecutive values. Daily: d = days since 1970-01-01. */
export interface PriceSeries {
  id: string;
  freq: 'D' | 'M';
  start?: string;
  d?: number[];
  v: (number | null)[];
}
